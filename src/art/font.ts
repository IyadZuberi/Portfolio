const glyph = (ch: string) => {
  const g = G[ch];
  if (!g) throw new Error(`no glyph for "${ch}"`);
  return g.split("|");
};

export const textWidth = (str: string) => [...str].reduce((w, ch) => w + glyph(ch)[0].length + 1, -1);

// Draws text with its top-left at (x, y); returns the width. shadow = drop shadow 1px right and down.
export function text(s: Sprite, x: number, y: number, str: string, colour: ColourKey = "slate", shadow: ColourKey | null = "gray1") {
  let cx = x;
  for (const ch of str) {
    const rows = glyph(ch);
    rows.forEach((row, dy) =>
      [...row].forEach((b, dx) => {
        if (b !== "#") return;
        if (shadow) {
          put(s, cx + dx + 1, y + dy, shadow);
          put(s, cx + dx, y + dy + 1, shadow);
          put(s, cx + dx + 1, y + dy + 1, shadow);
        }
      }),
    );
    rows.forEach((row, dy) => [...row].forEach((b, dx) => b === "#" && put(s, cx + dx, y + dy, colour)));
    cx += rows[0].length + 1;
  }
  return cx - x - 1;
}
